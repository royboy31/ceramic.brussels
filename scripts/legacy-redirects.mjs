#!/usr/bin/env node
/**
 * The old site's URLs, redirected to the new ones. Runs after `astro build`
 * (and scripts/pages-worker.mjs) and appends the rules to dist/_redirects.
 *
 * The map below names each old page by its English slug and says which new
 * page replaces it, as an English path. Everything else is derived:
 *
 * - The old FR/NL slugs come from legacy-export/normalized, which holds every
 *   slug the old CMS had, per locale. The old router answered any of a page's
 *   slugs under any language prefix (/nl/candidatures-galeries worked), and
 *   every section of a long page was also its own URL (/en/faq, /en/team), so
 *   each of those slugs gets a rule under /en, /fr and /nl.
 * - The FR/NL target is read from the built English page's hreflang links.
 *   When the FR/NL slugs change, the rules follow on the next build; there is
 *   no second copy of the map to keep in step.
 *
 * Every target is checked against the build: a rule pointing at a page that
 * was not built fails the build instead of shipping a redirect to a 404.
 * Targets carry the trailing slash, because Pages answers the slashless form
 * with a 308 of its own and the old URL would take two hops. An old URL that
 * is also a new page (/en/programme was an alias of food & drinks; it is the
 * programme hub now) keeps its new meaning.
 *
 * In-page anchors (/en/visitors-info#faq) cannot be redirected: the fragment
 * never reaches the server. The browser carries it across the 301, so such a
 * link lands at the top of the hub (/en/visit/#faq) rather than on its tab.
 *
 *   node scripts/legacy-redirects.mjs                generate (part of `npm run build`)
 *   node scripts/legacy-redirects.mjs --doc          every URL in docs/legacy-site-inventory.md has a rule
 *   node scripts/legacy-redirects.mjs --check <url>  every rule answers 301, one hop, onto a 200, on that host
 *
 * --doc and --check read the rules from dist/_redirects, so build first.
 */
