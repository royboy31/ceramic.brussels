/* ---------- generate ---------- */

function generate() {
  const legacy = (file) => JSON.parse(fs.readFileSync(path.resolve('legacy-export/normalized', file), 'utf8'));
  const rules = new Map();
  const live = [];

  const add = (from, to) => {
    // An old URL that is also a new page keeps its new meaning.
    if (isPage(from + '/')) {
      if (from + '/' !== to) live.push(from);
      to = from + '/';
    }
    const had = rules.get(from);
    if (had && had !== to) fail(`${from} maps to both ${had} and ${to}`);
    rules.set(from, to);
  };

  for (const lang of LANGS) {
    for (const page of legacy('pages.json')) {
      const to = PAGES[page.slug.en];
      if (to === undefined) fail(`old page "${page.slug.en}" (id ${page.id}) has no entry in PAGES`);
      for (const slug of slugsOf(page)) add(`/${lang}/${slug}`, target(lang, to));
    }
    for (const page of legacy('pastEditions.json')) {
      for (const slug of slugsOf(page)) add(`/${lang}/pasteditions/${slug}`, target(lang, 'editions'));
    }
    for (const [from, to] of Object.entries(ALIASES)) add(`/${lang}${from ? '/' + from : ''}`, target(lang, to));
  }
  for (const [from, to] of Object.entries(UNPREFIXED)) add(`/${from}`, target('en', to));
  for (const [from, to] of Object.entries(FILES)) {
    if (!fs.existsSync(path.join(DIST, to))) fail(`${from} → ${to}, which is not in the build`);
    rules.set(from, to);
  }

  const file = path.join(DIST, '_redirects');
  const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  const kept = before.split(MARKER)[0].trimEnd();
  const existing = kept.split('\n').filter((l) => l.trim() && !l.trim().startsWith('#')).length;
  if (existing + rules.size > PAGES_LIMIT) fail(`${existing + rules.size} rules, over the Pages limit of ${PAGES_LIMIT}`);

  const lines = [...rules].map(([from, to]) => `${from} ${to} 301`);
  fs.writeFileSync(file, `${kept}\n\n${MARKER}\n${lines.join('\n')}\n`);
  console.log(
    `[legacy-redirects] ${rules.size} rules appended to dist/_redirects` +
      (live.length ? `; ${live.length} old URLs are new pages too and keep their new meaning` : ''),
  );
}

function slugsOf(page) {
  const slugs = new Set(Object.values(page.slug ?? {}).filter(Boolean));
  for (const slug of slugs) {
    if (!/^[a-z0-9-]+$/.test(slug)) fail(`old slug "${slug}" (id ${page.id}) is not a plain path segment`);
  }
  return slugs;
}

/** The built page for a new English path, in `lang`: its own path, or its hreflang alternate. */
function target(lang, to) {
  const en = `/en/${to ? to + '/' : ''}`;
  if (!isPage(en)) fail(`target ${en} was not built`);
  if (lang === 'en') return en;
  const html = fs.readFileSync(path.join(DIST, en, 'index.html'), 'utf8');
  const tag = html.match(new RegExp(`<link[^>]*hreflang="${lang}"[^>]*>`))?.[0];
  const href = tag?.match(/href="([^"]+)"/)?.[1];
  const localised = href ? new URL(href).pathname.replace(/\/?$/, '/') : `/${lang}/${to ? to + '/' : ''}`;
  if (!isPage(localised)) fail(`target ${localised} (the ${lang} of ${en}) was not built`);
  return localised;
}

function isPage(p) {
  return fs.existsSync(path.join(DIST, p, 'index.html'));
}

/* ---------- --doc: the inventory's URLs all have a rule ---------- */

function doc() {
  const rules = readRules();
  const text = fs.readFileSync(path.resolve('docs/legacy-site-inventory.md'), 'utf8');
  const section = (from, to) => text.slice(text.indexOf(from), to ? text.indexOf(to) : undefined);
  const wanted = new Set();

  // Every /en, /fr, /nl path written out anywhere, with or without the host; fragments dropped.
  // The lookbehind keeps "(be/fr/us)" and "fr/en/nl" in the prose out.
  for (const m of text.matchAll(/(?:https?:\/\/(?:www\.)?ceramic\.brussels|(?<![\w/.-]))(\/(?:en|fr|nl)(?:\/[a-z0-9-]+)*)(?![\w-])/g)) {
    wanted.add(m[1]);
  }
  // 1.2: slugs that also resolved, under every prefix.
  for (const row of section('### 1.2', '### 1.3').split('\n').filter((l) => l.startsWith('| ') && !l.startsWith('| Page'))) {
    const aliases = row.split('|').at(-2);
    for (const m of aliases.matchAll(/`([a-z0-9/-]+)`/g)) for (const l of LANGS) wanted.add(`/${l}/${m[1]}`);
  }
  // 1.3: each anchor was also a page of its own.
  for (const m of section('### 1.3', '### 1.4').matchAll(/#([a-z0-9-]+)/g)) for (const l of LANGS) wanted.add(`/${l}/${m[1]}`);
  // 1.4: the past-edition subpages, in every language.
  for (const m of section('### 1.4', '### 1.5').matchAll(/^\| \d{4} \| `([a-z0-9-]+)`/gm)) {
    for (const l of LANGS) wanted.add(`/${l}/pasteditions/${m[1]}`);
  }
  // 1.5: the old sitemap's language-less URLs, and ceramic.brussels/awards and /collaborations.
  for (const m of section('### 1.5', '### 1.6').matchAll(/`(\/[a-z0-9-]+)`/g)) wanted.add(m[1]);
  for (const m of text.matchAll(/ceramic\.brussels\/(awards|collaborations)\b/g)) wanted.add(`/${m[1]}`);
  // Old favicons (the others are still at the same path).
  for (const m of text.matchAll(/`(\/favicon-\d+x\d+\.png)`/g)) wanted.add(m[1]);

  // Never pages on the old site (section 5, "no privacy policy exists").
  const neverExisted = new Set(['/en/privacy']);
  const missing = [...wanted].filter((p) => !neverExisted.has(p) && p !== '/' && !rules.has(p)).sort();
  // With the Cloudflare adapter Astro writes / → /en/ into _redirects; without it, as a meta refresh.
  const rootOk = /^\/\s+\/en\/\s+30[18]\s*$/m.test(fs.readFileSync(path.join(DIST, '_redirects'), 'utf8')) || isRootRedirect();

  console.log(`[legacy-redirects] ${wanted.size} URLs in the inventory, ${rules.size} rules`);
  if (!rootOk) console.log('  / does not redirect to /en/ in one hop');
  for (const p of missing) console.log(`  no rule: ${p}`);
  if (missing.length || !rootOk) process.exit(1);
  console.log('  every inventory URL has a rule');
}

function isRootRedirect() {
  const html = fs.existsSync(path.join(DIST, 'index.html')) ? fs.readFileSync(path.join(DIST, 'index.html'), 'utf8') : '';
  return /url=\/en\/"/.test(html);
}

/* ---------- --check <url>: live, against a deployment ---------- */

async function check(base) {
  if (!base) fail('usage: --check https://host');
  base = base.replace(/\/$/, '');
  const rules = readRules();
  rules.set('/', '/en/');
  const failures = [];
  const queue = [...rules];

  await Promise.all(
    Array.from({ length: 12 }, async () => {
      for (let item = queue.shift(); item; item = queue.shift()) {
        const [from, to] = item;
        try {
          const hop = await fetch(base + from, { method: 'HEAD', redirect: 'manual' });
          const location = hop.headers.get('location');
          const next = location ? new URL(location, base + from) : null;
          if (hop.status !== 301) failures.push(`${from}: ${hop.status}, expected 301`);
          else if (!next || next.origin !== base || next.pathname !== to) failures.push(`${from}: → ${location}, expected ${to}`);
          else {
            const page = await fetch(next, { method: 'HEAD', redirect: 'manual' });
            if (page.status !== 200) failures.push(`${from}: → ${to}, which answers ${page.status}`);
          }
        } catch (err) {
          failures.push(`${from}: ${err.message}`);
        }
      }
    }),
  );

  console.log(`[legacy-redirects] ${rules.size} old URLs checked against ${base}`);
  for (const f of failures.sort()) console.log(`  ${f}`);
  if (failures.length) process.exit(1);
  console.log('  every one answers 301 in a single hop onto a page that answers 200');
}

function readRules() {
  const file = path.join(DIST, '_redirects');
  const text = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (!text.includes(MARKER)) fail('dist/_redirects has no generated rules: run the build first');
  const rules = new Map();
  for (const line of text.split(MARKER)[1].split('\n')) {
    const [from, to] = line.trim().split(/\s+/);
    if (from && to) rules.set(from, to);
  }
  return rules;
}

function fail(message) {
  console.error(`[legacy-redirects] ${message}`);
  process.exit(1);
}
