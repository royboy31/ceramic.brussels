export type StringKey = keyof (typeof STRINGS)['en'];

export function useTranslations(lang: LocaleId) {
  return function t(key: StringKey, vars?: Record<string, string | number>): string {
    let out: string = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
    return out;
  };
}

/** Build a locale-prefixed path. */
export function localePath(lang: LocaleId, path = ''): string {
  const clean = path.replace(/^\/+|\/+$/g, '');
  return clean ? `/${lang}/${clean}` : `/${lang}`;
}

export function formatDate(value: string | undefined, lang: LocaleId): string {
  if (!value) return '';
  const locale = { en: 'en-GB', fr: 'fr-BE', nl: 'nl-BE' }[lang];
  return new Intl.DateTimeFormat(locale, {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(new Date(value));
}

export function formatDateRange(start: string, end: string, lang: LocaleId): string {
  if (!start || !end) return '';
  const locale = { en: 'en-GB', fr: 'fr-BE', nl: 'nl-BE' }[lang];
  return new Intl.DateTimeFormat(locale, {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).formatRange(new Date(start), new Date(end));
}

export function formatTime(value: string | undefined, lang: LocaleId): string {
  if (!value) return '';
  const locale = { en: 'en-GB', fr: 'fr-BE', nl: 'nl-BE' }[lang];
  return new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit' }).format(
    new Date(value),
  );
}

/** "Thursday 21 January" - the day headings of the programme. */
export function formatDay(value: string | undefined, lang: LocaleId): string {
  if (!value) return '';
  const locale = { en: 'en-GB', fr: 'fr-BE', nl: 'nl-BE' }[lang];
  return new Intl.DateTimeFormat(locale, { weekday: 'long', day: 'numeric', month: 'long' }).format(
    new Date(value),
  );
}
